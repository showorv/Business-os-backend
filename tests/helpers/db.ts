import { prisma } from "../../src/lib/prisma.js";

// audit_logs rejects TRUNCATE by design, so tests lift its triggers just long enough to clean up.
// DELETE for the rest, because TRUNCATE ... CASCADE would also wipe the roles seeded by migration.
export const resetDatabase = () =>
  prisma.$transaction([
    prisma.$executeRawUnsafe(`ALTER TABLE audit_logs DISABLE TRIGGER USER`),
    prisma.$executeRawUnsafe(`TRUNCATE audit_logs RESTART IDENTITY`),
    prisma.$executeRawUnsafe(`ALTER TABLE audit_logs ENABLE TRIGGER USER`),
    prisma.$executeRawUnsafe(`DELETE FROM ai_tool_calls`),
    prisma.$executeRawUnsafe(`DELETE FROM ai_messages`),
    prisma.$executeRawUnsafe(`DELETE FROM ai_proposals`),
    prisma.$executeRawUnsafe(`DELETE FROM ai_conversations`),
    prisma.$executeRawUnsafe(`DELETE FROM document_chunks`),
    prisma.$executeRawUnsafe(`DELETE FROM statement_line_links`),
    prisma.$executeRawUnsafe(`DELETE FROM statement_lines`),
    prisma.$executeRawUnsafe(`DELETE FROM statement_imports`),
    prisma.$executeRawUnsafe(`DELETE FROM statement_rules`),
    prisma.$executeRawUnsafe(`DELETE FROM statement_templates`),
    prisma.$executeRawUnsafe(`DELETE FROM raw_payloads`),
    prisma.$executeRawUnsafe(`DELETE FROM sync_runs`),
    prisma.$executeRawUnsafe(`DELETE FROM integration_connections`),
    prisma.$executeRawUnsafe(`DELETE FROM notifications`),
    prisma.$executeRawUnsafe(`DELETE FROM notification_preferences`),
    prisma.$executeRawUnsafe(`DELETE FROM push_subscriptions`),
    prisma.$executeRawUnsafe(`DELETE FROM password_reset_tokens`),
    prisma.$executeRawUnsafe(`DELETE FROM recurring_runs`),
    prisma.$executeRawUnsafe(`DELETE FROM recurring_schedules`),
    prisma.$executeRawUnsafe(`DELETE FROM reminders`),
    prisma.$executeRawUnsafe(`DELETE FROM task_attachments`),
    prisma.$executeRawUnsafe(`DELETE FROM task_comments`),
    prisma.$executeRawUnsafe(`DELETE FROM tasks`),
    prisma.$executeRawUnsafe(`DELETE FROM report_exports`),
    prisma.$executeRawUnsafe(`DELETE FROM goals`),
    prisma.$executeRawUnsafe(`DELETE FROM budget_alerts`),
    prisma.$executeRawUnsafe(`DELETE FROM budget_lines`),
    prisma.$executeRawUnsafe(`DELETE FROM budgets`),
    prisma.$executeRawUnsafe(`DELETE FROM outbox_events`),
    prisma.$executeRawUnsafe(`DELETE FROM exchange_rates`),
    prisma.$executeRawUnsafe(`DELETE FROM intercompany_transfers`),
    prisma.$executeRawUnsafe(`DELETE FROM ledger_monthly_rollups`),
    prisma.$executeRawUnsafe(`DELETE FROM reconciliation_lines`),
    prisma.$executeRawUnsafe(`DELETE FROM reconciliations`),
    prisma.$executeRawUnsafe(`DELETE FROM transaction_attachments`),
    prisma.$executeRawUnsafe(`DELETE FROM transactions`),
    prisma.$executeRawUnsafe(`DELETE FROM documents`),
    prisma.$executeRawUnsafe(`ALTER TABLE journal_lines DISABLE TRIGGER USER`),
    prisma.$executeRawUnsafe(`ALTER TABLE journal_entries DISABLE TRIGGER USER`),
    prisma.$executeRawUnsafe(`DELETE FROM journal_lines`),
    prisma.$executeRawUnsafe(`DELETE FROM journal_entries`),
    prisma.$executeRawUnsafe(`ALTER TABLE journal_entries ENABLE TRIGGER USER`),
    prisma.$executeRawUnsafe(`ALTER TABLE journal_lines ENABLE TRIGGER USER`),
    prisma.$executeRawUnsafe(`DELETE FROM categories`),
    prisma.$executeRawUnsafe(`DELETE FROM financial_accounts`),
    prisma.$executeRawUnsafe(`DELETE FROM ledger_accounts`),
    prisma.$executeRawUnsafe(`DELETE FROM fiscal_periods`),
    prisma.$executeRawUnsafe(`DELETE FROM business_sequences`),
    prisma.$executeRawUnsafe(`DELETE FROM idempotency_keys`),
    prisma.$executeRawUnsafe(`DELETE FROM invitations`),
    prisma.$executeRawUnsafe(`DELETE FROM business_members`),
    prisma.$executeRawUnsafe(`DELETE FROM businesses`),
    prisma.$executeRawUnsafe(`DELETE FROM payments`),
    prisma.$executeRawUnsafe(`DELETE FROM users`),
    prisma.$executeRawUnsafe(`DELETE FROM workspaces`),
  ]);

export const auditActions = async () =>
  (await prisma.auditLog.findMany({ orderBy: { id: "asc" } })).map((row) => row.action);
